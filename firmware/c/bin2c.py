#!/usr/bin/env python3
"""Turn a raw firmware image into a C byte array for the OTA updater."""
import sys

src, dst, name = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(src, "rb").read()
with open(dst, "w", encoding="utf-8") as f:
    f.write("// Generated by bin2c.py from %s\n" % src)
    f.write("#include <stdint.h>\n")
    f.write("const uint32_t %s_len = %du;\n" % (name, len(data)))
    f.write("const uint8_t %s[] __attribute__((aligned(4))) = {\n" % name)
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        f.write("    " + ", ".join("0x%02x" % b for b in chunk) + ",\n")
    f.write("};\n")
